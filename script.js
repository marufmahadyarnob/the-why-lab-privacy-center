function readStorage(key) {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
}

function writeStorage(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch {
    // Storage may be blocked in private browsing contexts
  }
}

function snapshotEnglish() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    enSnapshot.ui[el.dataset.i18n] = el.textContent;
  });

  const article = document.getElementById('policy-article');
  if (article) {
    enSnapshot.policyNodes = Array.from(article.children).map((node) => node.cloneNode(true));
  }

  document.querySelectorAll('#faq-list .faq-item').forEach((item) => {
    enSnapshot.faq.push({
      q: item.querySelector('.faq-btn span').textContent,
      a: item.querySelector('.faq-answer p').textContent,
    });
  });
}

function showToast(message, isError = false) {
  const toast = document.getElementById('toast');
  if (!toast) return;

  toast.textContent = message;
  toast.classList.toggle('is-error', isError);
  toast.classList.add('is-visible');

  clearTimeout(toastTimeout);
  toastTimeout = setTimeout(() => toast.classList.remove('is-visible'), 3000);
}

async function copyToClipboard(text, successMsg) {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      showToast(successMsg);
      return;
    }
  } catch {
    // Fall through to legacy textarea copy
  }

  const input = document.createElement('textarea');
  input.value = text;
  input.setAttribute('readonly', '');
  input.style.position = 'fixed';
  input.style.opacity = '0';
  document.body.appendChild(input);
  input.select();

  const copied = document.execCommand('copy');
  input.remove();
  showToast(copied ? successMsg : META[activeLang].copyFailed, !copied);
}

function renderPolicy(lang) {
  const article = document.getElementById('policy-article');
  if (!article) return;

  article.textContent = '';

  if (lang === 'en') {
    enSnapshot.policyNodes.forEach((node) => article.appendChild(node.cloneNode(true)));
    return;
  }

  const mailHref = `mailto:${CONFIG.email}?subject=${encodeURIComponent(CONFIG.subject)}`;

  BN_POLICY.forEach((sec) => {
    const section = document.createElement('section');
    section.className = 'policy-block';
    section.id = sec.id;

    const h3 = document.createElement('h3');
    const num = document.createElement('span');
    num.className = 'policy-num';
    num.textContent = sec.num;
    const title = document.createElement('span');
    title.textContent = sec.title;
    h3.append(num, title);
    section.appendChild(h3);

    sec.blocks.forEach((block) => {
      if (typeof block === 'string') {
        const p = document.createElement('p');
        p.textContent = block;
        section.appendChild(p);
      } else if (Array.isArray(block)) {
        const ul = document.createElement('ul');
        block.forEach((line) => {
          const li = document.createElement('li');
          li.textContent = line;
          ul.appendChild(li);
        });
        section.appendChild(ul);
      } else if (block.callout) {
        const box = document.createElement('div');
        box.className = 'policy-callout';

        const brandP = document.createElement('p');
        const strong = document.createElement('strong');
        strong.textContent = 'The Why Lab';
        brandP.appendChild(strong);

        const emailP = document.createElement('p');
        emailP.append(`${block.emailLabel}: `);
        const link = document.createElement('a');
        link.className = 'inline-link';
        link.href = mailHref;
        link.textContent = CONFIG.email;
        emailP.appendChild(link);

        const subjectP = document.createElement('p');
        subjectP.textContent = block.subject;

        box.append(brandP, emailP, subjectP);
        section.appendChild(box);
      }
    });

    article.appendChild(section);
  });
}

function buildToc() {
  const sections = document.querySelectorAll('#policy-article .policy-block');
  const targets = [
    { el: document.getElementById('toc-desktop-list'), closeOnClick: false },
    { el: document.getElementById('toc-mobile-list'), closeOnClick: true },
  ];

  targets.forEach(({ el, closeOnClick }) => {
    if (!el) return;
    el.textContent = '';

    sections.forEach((sec, idx) => {
      const li = document.createElement('li');
      const a = document.createElement('a');
      a.className = idx === 0 ? 'toc-link is-active' : 'toc-link';
      a.href = `#${sec.id}`;
      a.dataset.target = sec.id;

      const num = document.createElement('span');
      num.className = 'toc-num';
      num.textContent = sec.querySelector('.policy-num')?.textContent || '';

      const label = document.createElement('span');
      label.textContent = sec.querySelector('h3 span:last-child')?.textContent || '';

      a.append(num, label);

      if (closeOnClick) {
        a.addEventListener('click', () => {
          const drawer = document.getElementById('toc-mobile');
          if (drawer) drawer.open = false;
        });
      }

      li.appendChild(a);
      el.appendChild(li);
    });
  });
}

function observeSections() {
  if (tocObserver) tocObserver.disconnect();
  if (!('IntersectionObserver' in window)) return;

  const sections = document.querySelectorAll('#policy-article .policy-block');
  tocObserver = new IntersectionObserver(
    (entries) => {
      const visible = entries
        .filter((e) => e.isIntersecting)
        .sort((a, b) => a.boundingClientRect.top - b.boundingClientRect.top);

      if (!visible.length) return;
      const activeId = visible[0].target.id;

      document.querySelectorAll('.toc-link').forEach((link) => {
        const match = link.dataset.target === activeId;
        link.classList.toggle('is-active', match);
        if (match) link.setAttribute('aria-current', 'location');
        else link.removeAttribute('aria-current');
      });
    },
    { rootMargin: '-96px 0px -65% 0px', threshold: 0 }
  );

  sections.forEach((sec) => tocObserver.observe(sec));
}

